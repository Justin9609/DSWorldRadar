-- Resolve paths from this script itself. v1.18.7-v1.18.9 used a working-directory
-- relative "Mods/DSWorldRadar/..." path; UE4SS can start Lua with a different CWD,
-- making the actor bridge silently fail to create its queue/log. This is now independent
-- of process CWD and always points back to this DSWorldRadar folder.
local function script_source_path()
  local ok, info = pcall(function()
    if debug == nil or debug.getinfo == nil then return nil end
    return debug.getinfo(1, "S")
  end)
  if not ok or info == nil then return "" end
  local src = tostring(info.source or "")
  if src:sub(1,1) == "@" then src = src:sub(2) end
  return (src:gsub("\\", "/"))
end

