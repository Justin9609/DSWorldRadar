local function queue(sid, source, cls, x,y,z, object_id)
  local key=tostring(sid)
  if emitted[key] then return end
  local f=io.open(QUEUE_PATH,"a")
  if not f then log("QUEUE_OPEN_FAILED sid="..key.." source="..source); return end
  local wrote=f:write("DSC_",key,"|",source,"|",cls,"|",string.format("%.1f|%.1f|%.1f",x,y,z),"|",tostring(object_id or -1),"|",tostring(os.time()),"\n")
  local closed=f:close()
  if not wrote or not closed then log("QUEUE_WRITE_FAILED sid="..key); return end
  emitted[key]=true
  log("TREASURE_OPENED_ACTOR DSC_"..key.." source="..source.." class="..cls)
end

local function queue_candidate(sid, source, cls, x,y,z, object_id)
  local key=tostring(sid)
  local emit_key="candidate:"..key
  if emitted[emit_key] then return end
  local f=io.open(QUEUE_PATH,"a")
  if not f then log("CANDIDATE_QUEUE_OPEN_FAILED sid="..key.." source="..source); return end
  local wrote=f:write("DSC_",key,"|candidate_",source,"|",cls,"|",string.format("%.1f|%.1f|%.1f",x,y,z),"|",tostring(object_id or -1),"|",tostring(os.time()),"\n")
  local closed=f:close()
  if not wrote or not closed then log("QUEUE_WRITE_FAILED sid="..key); return end
  emitted[emit_key]=true
  log("TREASURE_CANDIDATE_ACTOR DSC_"..key.." source="..source.." class="..cls.." confirmation=save_positive_only")
end

local function correlate(receiver, source, actor_param, require_local_actor, force_candidate)
  consume_save_boundary_reset()
  if receiver == nil then return end
  local cls=class_name(receiver)
  local arr=cls and catalog[cls] or nil
  if arr == nil then return end
  local x,y,z=loc(receiver)
  if x == nil then return end

  local pawn=local_pawn()
  local candidate_only = force_candidate == true
  if require_local_actor then
    local accepted=false
    if pawn ~= nil and actor_param ~= nil and same_obj(actor_param,pawn) then accepted=true end
    if not accepted and pawn ~= nil and actor_param ~= nil and mount_only[cls] then
      local rider=safe(function() return pawn.Rider end)
      -- 2.2.1 semantics: Rider evidence is accepted only for the three mount-only
      -- treasure classes and only when Rider/Pawn belong to the same non-null World.
      if rider ~= nil and same_obj(actor_param,rider) and same_world(actor_param,pawn) then accepted=true end
    end
    -- A rejected/non-Pawn interaction is not completion evidence. Keep the exact
    -- receiver as a candidate and require the save-positive path to confirm it.
    if not accepted then candidate_only=true end
  end

  -- Preserve the original eight-metre receiver bound to the fresh local player.
  if pawn ~= nil then
    local px,py,pz=loc(pawn)
    if px ~= nil then
      local pd2=(x-px)^2+(y-py)^2+(z-pz)^2
      if pd2 > MAX_D2 then return end
    end
  elseif actor_param ~= nil then
    local ax,ay,az=loc(actor_param)
    if ax ~= nil and ((x-ax)^2+(y-ay)^2+(z-az)^2 > MAX_D2) then return end
  end

  local best,bestd=nil,1e100
  for i=1,#arr do
    local r=arr[i]
    local d=(x-r[2])^2+(y-r[3])^2+(z-r[4])^2
    if d < bestd then bestd=d; best=r end
  end
  if best == nil or bestd > MAX_D2 then return end
  local oid=safe(function() return receiver.ObjectID end)
  if candidate_only then
    queue_candidate(best[1],source,cls,x,y,z,oid)
  else
    queue(best[1],source,cls,x,y,z,oid)
  end
end

local function hook(path, pre)
  local ok, a,b = pcall(function()
