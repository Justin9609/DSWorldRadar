local function write_atomic_text(path,body)
  local tmp=path..".tmp"
  local f=io.open(tmp,"wb")
  if not f then return false end
  local wrote=f:write(body,body:sub(-1)=="\n" and "" or "\n")
  local closed=f:close()
  if not wrote or not closed then return false end
  local ok,result=pcall(os.rename,tmp,path)
  if ok and result then return true end
  -- Windows rename cannot replace an existing destination. Publish only the
  -- complete temporary file; readers retry a missing path, never a partial copy.
  pcall(os.remove,path)
  ok,result=pcall(os.rename,tmp,path)
  return ok and result and true or false
end

