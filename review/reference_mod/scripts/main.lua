  for line in f:lines() do
    if first then
      first=false
    else
      line=(line or ""):gsub("\r","")
      local id,kind=line:match("^([^,]+),([^,]+),")
      if kind=="area_quests" then
        local q=tonumber(id)
        if q~=nil and not area_catalog[q] then
          area_catalog[q]=true
          area_catalog_count=area_catalog_count+1
        end
      end
    end
  end
  f:close()

  if area_catalog_count~=147 then
    area_catalog_error="area-catalog-coverage-"..tostring(area_catalog_count)
    return false
  end
  area_catalog_error="ok"
  return true
end

